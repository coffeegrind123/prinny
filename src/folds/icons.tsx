// Icon fill strategy. Lucide is a stroke-based line set with no solid
// variants, so a `filled` cue cannot be auto-derived. Only icons that look good
// as a solid silhouette get the fill treatment (`solid`); the rest render a
// crisp outline and ignore `filled` (`outline`). Add names to SOLID as you
// verify each one; defaults to outline so nothing renders as a blob.
// createElement (not JSX) keeps these off the react/function-component-definition
// rule, since these are folds render functions, not React components.
const SOLID = new Set<string>(['Star']);

const outline =
  (Comp: LucideIcon): IconSrc =>
  () =>
    React.createElement(Comp, {
      width: '100%',
      height: '100%',
      fill: 'none',
      stroke: 'currentColor',
    });

const solid =
  (Comp: LucideIcon): IconSrc =>
  (filled) =>
    React.createElement(Comp, {
      width: '100%',
      height: '100%',
      fill: filled ? 'currentColor' : 'none',
      stroke: filled ? 'none' : 'currentColor',
    });

// Picks `solid` for whitelisted names, `outline` otherwise.
const makeIcon = (name: IconName, Comp: LucideIcon): IconSrc =>
  SOLID.has(name) ? solid(Comp) : outline(Comp);

